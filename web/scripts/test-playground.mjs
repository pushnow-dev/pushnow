import assert from 'node:assert/strict';
import { startBackendFixture } from '../../sdk/typescript/test/helpers/backend-fixture.mjs';
import { openV2 } from '../../cli/test/v2-fixtures.js';
import { approveFixtureBrowser } from './playground-authorization.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:4325';
const backend = await startBackendFixture({ corsOrigins: [new URL(base).origin] });
let browser;
try {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.context().grantPermissions(['local-network-access'], { origin: new URL(base).origin });
  page.on('pageerror', error => console.error('Browser error:', error.message));
  await page.addInitScript(session => {
    if (!sessionStorage.getItem('pushnow.web.session')) sessionStorage.setItem('pushnow.web.session', JSON.stringify(session));
  }, backend.session);
  // Change only the development page's API configuration; all API calls use real HTTP/CORS to the disposable Worker.
  await page.route(`${base}/dashboard/`, async route => {
    const response = await route.fetch();
    await route.fulfill({ response, body: (await response.text()).replaceAll('https://api.pushnow.dev', backend.apiURL) });
  });
  await page.route('https://api.pushnow.dev/**', route => { throw new Error(`Unexpected production request: ${new URL(route.request().url()).pathname}`); });
  const messages = [];
  const messageHeaders = [];
  page.on('request', req => { if (new URL(req.url()).origin === backend.apiURL && new URL(req.url()).pathname === '/v2/messages' && req.method() === 'POST') {
    messages.push(req.postData()); messageHeaders.push(req.headers());
  } });
  await page.goto(`${base}/dashboard/`);
  const root = page.locator('[data-playground]');
  await page.locator('[data-playground][data-ready=true]').waitFor();
  await page.locator('[data-dashboard]:not([hidden])').waitFor();
  const importConfig = async config => {
    await root.locator('[data-import-config]').setInputFiles({ name: 'sender.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(config)) });
  };
  await importConfig({ ...backend.config, user_id: '00000000-0000-4000-8000-000000000001' });
  await page.waitForFunction(() => document.querySelector('[data-playground-status]').textContent.length > 0);
  assert.match(await root.locator('[data-playground-status]').textContent(), /does not belong/);
  await root.locator('[data-playground-status]').filter({ hasText: 'does not belong' }).waitFor();
  assert.equal(messages.length, 0);
  await importConfig(backend.config);
  await page.waitForFunction(() => !document.querySelector('[data-send-fields]').disabled);
  await root.locator('[name=title]').fill('Browser E2EE title');
  await root.locator('[name=body]').fill('Private dashboard body');
  await root.locator('[name=token]').fill('invalid-source-token');
  await root.locator('[type=submit]').click();
  await root.locator('[data-playground-status]').filter({ hasText: /401|unauthorized|invalid_source|invalid_key/i }).waitFor();
  assert.equal(messages.length, 0, 'invalid token cannot send a message');
  await root.locator('[name=token]').fill(backend.config.source_key);
  await root.locator('details').filter({hasText:'HTTP headers'}).locator('summary').click();
  await root.locator('[name=headers]').fill(JSON.stringify({Authorization:'not-allowed'}));
  await root.locator('[type=submit]').click();
  await root.locator('[data-playground-status]').filter({hasText:'Additional headers must use X-'}).waitFor();
  assert.equal(messages.length, 0, 'cannot override the authorization header');
  await root.locator('[name=headers]').fill(JSON.stringify({'X-Workflow-Run':'private-trace-value'}));
  await root.locator('[name=target]').selectOption('selected');
  await root.locator('[name=device]').first().check();
  await root.locator('[name=links]').fill('https://example.com/dashboard-detail');
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64');
  await root.locator('[name=icon]').setInputFiles({ name: 'icon.png', mimeType: 'image/png', buffer: png });
  await root.locator('[name=image]').setInputFiles({ name: 'preview.png', mimeType: 'image/png', buffer: png });
  await root.locator('[name=files]').setInputFiles({ name: 'report.txt', mimeType: 'text/plain', buffer: Buffer.from('Private attachment body') });
  await root.locator('[type=submit]').click();
  await root.locator('[data-playground-status]').filter({ hasText: 'API accepted' }).waitFor({ timeout: 30000 });
  assert.equal(messages.length, 1);
  const sent = JSON.parse(messages[0]);
  assert.equal(messageHeaders[0]['x-workflow-run'], 'private-trace-value');
  assert.deepEqual(sent.notify_device_ids, [backend.fixture.devices[0].id]);
  assert(!messages[0].includes('Private dashboard body'));
  const row = await backend.db.prepare('SELECT * FROM v2_messages WHERE id=?').bind(sent.message_id).first();
  const content = await openV2(backend.fixture, { ...row, message_id: row.id });
  assert.equal(content.title, 'Browser E2EE title');
  assert.equal(content.body, 'Private dashboard body');
  assert.equal(content.attachments.length, 3);
  assert(content.icon_id && content.image_id && content.icon_id !== content.image_id);
  assert.deepEqual(content.links, ['https://example.com/dashboard-detail']);
  await root.locator('[data-retry]').click();
  await root.locator('[data-playground-status]').filter({ hasText: 'Deduplicated' }).waitFor();
  assert.equal(messages[0], messages[1], 'retry preserves exact ciphertext and message ID');
  assert.equal((await backend.db.prepare('SELECT COUNT(*) AS n FROM v2_messages').first()).n, 1);
  const log = await root.locator('[data-http-log]').textContent();
  for (const secret of [backend.config.source_key, backend.config.sender_private_key, 'Private dashboard body', 'Private attachment body', 'private-trace-value']) assert(!log.includes(secret));
  assert(log.includes('[redacted]') && log.includes('/v2/messages') && log.includes('200'));
  assert(!(await page.evaluate(() => JSON.stringify(sessionStorage))).includes(backend.config.source_key));
  for (const name of ['icon', 'image', 'files']) await root.locator(`[name=${name}]`).setInputFiles([]);
  await root.locator('[name=delivery]').selectOption('inbox');
  await root.locator('[name=title]').fill('Inbox only');
  await root.locator('[type=submit]').click();
  await page.waitForFunction(() => document.querySelector('[data-playground-status]').textContent.includes('API accepted'));
  assert.deepEqual(JSON.parse(messages.at(-1)).notify_device_ids, []);
  await root.locator('[name=schedule]').selectOption('later');
  const due = new Date(Date.now() + 3600000); due.setSeconds(0, 0);
  const local = `${due.getFullYear()}-${String(due.getMonth()+1).padStart(2,'0')}-${String(due.getDate()).padStart(2,'0')}T${String(due.getHours()).padStart(2,'0')}:${String(due.getMinutes()).padStart(2,'0')}`;
  await root.locator('[name=scheduledAt]').fill(local);
  await root.locator('[type=submit]').click();
  await root.locator('[data-playground-status]').filter({ hasText: 'API accepted' }).waitFor();
  assert.equal(JSON.parse(messages.at(-1)).scheduled_at, due.toISOString());
  await root.locator('[name=delivery]').selectOption('push');
  await root.locator('[name=schedule]').selectOption('now');
  for (const sound of ['default','silent','chime']) {
    await root.locator('[name=sound]').selectOption(sound);
    await root.locator('[type=submit]').click();
    await root.locator('[data-playground-status]').filter({hasText:'API accepted'}).waitFor();
    const request = JSON.parse(messages.at(-1));
    assert.equal(request.sound, sound === 'default' ? undefined : sound);
    const stored = await backend.db.prepare('SELECT sound FROM v2_messages WHERE id=?').bind(request.message_id).first();
    assert.equal(stored.sound, sound === 'default' ? null : sound);
    await root.locator('[data-retry]').click();
    await root.locator('[data-playground-status]').filter({hasText:'Deduplicated'}).waitFor();
    assert.equal(messages.at(-1), messages.at(-2), 'sound retry retains identical request');
  }
  await root.locator('[data-authorize]').click();
  await root.locator('[data-authorization]:not([hidden])').waitFor();
  const approved = await approveFixtureBrowser(backend, (await root.locator('[data-approval-code]').textContent()).trim());
  await root.locator('[data-account-fingerprint]').fill(approved.fingerprint);
  await root.locator('[data-complete-authorization]').click();
  await root.locator('[data-sender-status]').filter({ hasText: approved.sourceId }).waitFor();
  await root.locator('[name=title]').fill('New browser authorization');
  await root.locator('[name=delivery]').selectOption('inbox');
  await root.locator('[type=submit]').click();
  await root.locator('[data-playground-status]').filter({ hasText: 'API accepted' }).waitFor();
  const authorizedMessage = JSON.parse(messages.at(-1));
  assert.equal((await backend.db.prepare('SELECT source_id FROM v2_messages WHERE id=?').bind(authorizedMessage.message_id).first()).source_id, approved.sourceId);
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 950 });
    await root.scrollIntoViewIfNeeded();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `No overflow at ${width}px`);
    await page.screenshot({ path: `/tmp/pushnow-dashboard-${width}.png`, fullPage: true });
  }
  await page.locator('[data-sign-out]').click();
  await page.locator('[data-dashboard][hidden]').waitFor({ state: 'attached' });
  assert.equal(await root.locator('[name=token]').inputValue(), '');
  assert.equal(await root.locator('[data-http-log]').textContent(), '');
  console.log('PASS actual browser HTTP/CORS + D1/R2: browser authorization, account isolation, token rejection, HPKE, icon/image/file/link, selected targets, inbox-only, schedule, default/silent/chime, extra headers, exact retry, redacted logs, logout cleanup and responsive widths');
} finally { await browser?.close(); await backend.close(); }
